"""Pure domain model for generated `/rapid-<modo>` harness shortcuts."""
from __future__ import annotations

from dataclasses import dataclass
import json
from typing import Mapping

GENERATED_MARKER = "<!-- generated by rapid shortcuts -->"

SHORTCUT_NAMES: tuple[str, ...] = (
    "rapid-feature",
    "rapid-bugfix",
    "rapid-refactor",
    "rapid-hardening",
    "rapid-research",
    "rapid-next",
    "rapid-status",
    "rapid-approve",
)

# Mode shortcuts need a playbook in templates/modes/<mode>.json to be generated.
MODE_SHORTCUTS: Mapping[str, str] = {
    "rapid-feature": "feature",
    "rapid-bugfix": "bugfix",
    "rapid-refactor": "refactor",
    "rapid-hardening": "hardening",
    "rapid-research": "research",
}

CONTEXT_PLACEHOLDER = "{{context_step}}"


class ShortcutTemplateError(ValueError):
    """Invalid shortcut template (RAPID1313)."""

    code = "RAPID1313"


@dataclass(frozen=True)
class ShortcutTemplate:
    """A harness-neutral shortcut: metadata plus a Markdown body."""

    name: str
    description: str
    body: str
    argument_hint: str | None = None
    mode: str | None = None
    context_command: str | None = None
    disable_model_invocation: bool = False
    allowed_commands: tuple[str, ...] = ()

    def render_body(self, context_step: str) -> str:
        return self.body.replace(CONTEXT_PLACEHOLDER, context_step)


def _parse_scalar(raw: str):
    raw = raw.strip()
    if raw in {"true", "false"}:
        return raw == "true"
    if raw.startswith('"'):
        return json.loads(raw)
    return raw


def parse_template(name: str, text: str) -> ShortcutTemplate:
    """Parse `templates/shortcuts/<name>.md` (flat `key: value` frontmatter)."""
    normalized = text.replace("\r\n", "\n")
    if not normalized.startswith("---\n"):
        raise ShortcutTemplateError(
            f"RAPID1313 Shortcut template '{name}' must start with frontmatter."
        )
    header, sep, body = normalized[4:].partition("\n---\n")
    if not sep:
        raise ShortcutTemplateError(
            f"RAPID1313 Shortcut template '{name}' has unterminated frontmatter."
        )

    fields: dict[str, object] = {}
    for line in header.splitlines():
        if not line.strip():
            continue
        key, colon, value = line.partition(":")
        if not colon:
            raise ShortcutTemplateError(
                f"RAPID1313 Shortcut template '{name}': invalid frontmatter line '{line}'."
            )
        try:
            fields[key.strip()] = _parse_scalar(value)
        except ValueError as exc:
            raise ShortcutTemplateError(
                f"RAPID1313 Shortcut template '{name}': invalid value for '{key.strip()}': {exc}"
            ) from exc

    description = fields.get("description")
    if not isinstance(description, str) or not description.strip():
        raise ShortcutTemplateError(
            f"RAPID1313 Shortcut template '{name}' requires a non-empty description."
        )
    body = body.strip("\n")
    if not body:
        raise ShortcutTemplateError(f"RAPID1313 Shortcut template '{name}' has an empty body.")

    allowed = fields.get("allowed-commands", "")
    return ShortcutTemplate(
        name=name,
        description=description,
        body=body + "\n",
        argument_hint=fields.get("argument-hint") or None,
        mode=fields.get("mode") or None,
        context_command=fields.get("context-command") or None,
        disable_model_invocation=fields.get("disable-model-invocation") is True,
        allowed_commands=tuple(part for part in str(allowed).split() if part),
    )


def has_generated_marker(text: str) -> bool:
    return GENERATED_MARKER in text
