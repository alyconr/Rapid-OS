"""Pure domain model for generated `/rapid-<modo>` harness shortcuts."""
from __future__ import annotations

from dataclasses import dataclass
import json
from typing import Iterable, Mapping, Sequence

GENERATED_MARKER = "<!-- generated by rapid shortcuts -->"

SHORTCUT_NAMES: tuple[str, ...] = (
    "rapid-feature",
    "rapid-bugfix",
    "rapid-refactor",
    "rapid-hardening",
    "rapid-research",
    "rapid-next",
    "rapid-status",
    "rapid-approve",
)

# Mode shortcuts need a playbook in templates/modes/<mode>.json to be generated.
MODE_SHORTCUTS: Mapping[str, str] = {
    "rapid-feature": "feature",
    "rapid-bugfix": "bugfix",
    "rapid-refactor": "refactor",
    "rapid-hardening": "hardening",
    "rapid-research": "research",
}

CONTEXT_PLACEHOLDER = "{{context_step}}"


class ShortcutTemplateError(ValueError):
    """Invalid shortcut template (RAPID1313)."""

    code = "RAPID1313"


@dataclass(frozen=True)
class ShortcutTemplate:
    """A harness-neutral shortcut: metadata plus a Markdown body."""

    name: str
    description: str
    body: str
    argument_hint: str | None = None
    mode: str | None = None
    context_command: str | None = None
    disable_model_invocation: bool = False
    allowed_commands: tuple[str, ...] = ()

    def render_body(self, context_step: str) -> str:
        return self.body.replace(CONTEXT_PLACEHOLDER, context_step)


def _parse_scalar(raw: str):
    raw = raw.strip()
    if raw in {"true", "false"}:
        return raw == "true"
    if raw.startswith('"'):
        return json.loads(raw)
    return raw


def parse_template(name: str, text: str) -> ShortcutTemplate:
    """Parse `templates/shortcuts/<name>.md` (flat `key: value` frontmatter)."""
    normalized = text.replace("\r\n", "\n")
    if not normalized.startswith("---\n"):
        raise ShortcutTemplateError(
            f"RAPID1313 Shortcut template '{name}' must start with frontmatter."
        )
    header, sep, body = normalized[4:].partition("\n---\n")
    if not sep:
        raise ShortcutTemplateError(
            f"RAPID1313 Shortcut template '{name}' has unterminated frontmatter."
        )

    fields: dict[str, object] = {}
    for line in header.splitlines():
        if not line.strip():
            continue
        key, colon, value = line.partition(":")
        if not colon:
            raise ShortcutTemplateError(
                f"RAPID1313 Shortcut template '{name}': invalid frontmatter line '{line}'."
            )
        try:
            fields[key.strip()] = _parse_scalar(value)
        except ValueError as exc:
            raise ShortcutTemplateError(
                f"RAPID1313 Shortcut template '{name}': invalid value for '{key.strip()}': {exc}"
            ) from exc

    description = fields.get("description")
    if not isinstance(description, str) or not description.strip():
        raise ShortcutTemplateError(
            f"RAPID1313 Shortcut template '{name}' requires a non-empty description."
        )
    body = body.strip("\n")
    if not body:
        raise ShortcutTemplateError(f"RAPID1313 Shortcut template '{name}' has an empty body.")

    allowed = fields.get("allowed-commands", "")
    return ShortcutTemplate(
        name=name,
        description=description,
        body=body + "\n",
        argument_hint=fields.get("argument-hint") or None,
        mode=fields.get("mode") or None,
        context_command=fields.get("context-command") or None,
        disable_model_invocation=fields.get("disable-model-invocation") is True,
        allowed_commands=tuple(part for part in str(allowed).split() if part),
    )


def has_generated_marker(text: str) -> bool:
    return GENERATED_MARKER in text


# --------------------------------------------------------------------------- folder overlaps

# Skill/prompt folders each harness generates its shortcuts in (see the adapters in
# rapid_os/adapters/agents/implementations.py; a test keeps this table in sync with them).
HARNESS_FOLDERS: Mapping[str, str] = {
    "claude": ".claude/skills",
    "codex": ".agents/skills",
    "antigravity": ".agents/skills",
    "cursor": ".cursor/skills",
    "vscode": ".github/prompts",
}

# Folders each tool reads, according to its official documentation (same table as the
# "Si combinas harnesses" section of docs/guides/shortcuts.md):
#   Cursor:  https://cursor.com/docs/context/skills
#            (.agents/skills and .cursor/skills; for compatibility .claude/skills and .codex/skills)
#   VS Code: https://code.visualstudio.com/docs/copilot/customization/agent-skills
#            (.github/skills, .claude/skills and .agents/skills) plus the prompt files in
#            .github/prompts, https://code.visualstudio.com/docs/copilot/customization/prompt-files
TOOL_READ_FOLDERS: Mapping[str, tuple[str, ...]] = {
    "cursor": (".cursor/skills", ".agents/skills", ".claude/skills", ".codex/skills"),
    "vscode": (".github/skills", ".claude/skills", ".agents/skills", ".github/prompts"),
}

TOOL_LABELS: Mapping[str, str] = {"cursor": "Cursor", "vscode": "VS Code / Copilot"}
OVERLAP_CODE = "RAPID1321"
OVERLAP_DOC_URL = "https://alyconr.github.io/Rapid-OS/guides/shortcuts#si-combinas-harnesses"


@dataclass(frozen=True)
class FolderOverlap:
    """The same /rapid-* left in two folders that one tool reads."""

    reader: str  # cursor | vscode
    harnesses: tuple[str, ...]  # the reader's own harness first, then the overlapping ones
    folders: tuple[str, ...]

    @property
    def message(self) -> str:
        label = TOOL_LABELS[self.reader]
        others = tuple(h for h in self.harnesses if h != self.reader)
        recommended = " ".join(f"--harness {h}" for h in _dedupe_by_folder(others))
        return (
            f"{OVERLAP_CODE} {label} reads {', '.join(self.folders)}: selecting {', '.join(self.harnesses)} "
            f"leaves the same /rapid-* shortcuts in more than one of them. Its documentation does not say "
            f"how it shows same-named skills in different folders. Recommended: install only "
            f"{recommended} (without {self.reader}), since {label} already reads those folders. "
            f"See {OVERLAP_DOC_URL}"
        )

    def to_dict(self) -> dict:
        return {
            "code": OVERLAP_CODE,
            "message": self.message,
            "reader": self.reader,
            "harnesses": list(self.harnesses),
            "folders": list(self.folders),
        }


def _dedupe_by_folder(harness_ids: Sequence[str]) -> tuple[str, ...]:
    """One harness per folder (codex and antigravity share .agents/skills)."""
    seen: set[str] = set()
    kept: list[str] = []
    for harness in harness_ids:
        folder = HARNESS_FOLDERS[harness]
        if folder not in seen:
            seen.add(folder)
            kept.append(harness)
    return tuple(kept)


def detect_folder_overlaps(harness_ids: Iterable[str]) -> list[FolderOverlap]:
    """Overlaps in a harness selection: a reader tool that also reads another harness' folder.

    cursor/vscode alone, or together, do not overlap (Cursor does not read .github/prompts and
    VS Code does not read .cursor/skills); codex + antigravity share one folder.
    """
    selected = [h for h in dict.fromkeys(harness_ids) if h in HARNESS_FOLDERS]
    overlaps: list[FolderOverlap] = []
    for reader, read_folders in TOOL_READ_FOLDERS.items():
        if reader not in selected:
            continue
        others = [h for h in selected if h != reader and HARNESS_FOLDERS[h] in read_folders]
        if not others:
            continue
        folders = tuple(dict.fromkeys([HARNESS_FOLDERS[reader], *(HARNESS_FOLDERS[h] for h in others)]))
        overlaps.append(FolderOverlap(reader, (reader, *others), folders))
    return overlaps
